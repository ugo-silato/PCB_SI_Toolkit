def _near_track(x, y, dist=1.0):
    """True if the point is within 'dist' mm of a track edge."""
    for sx0, sy0, sx1, sy1, sw in M["segments"]:
        dx, dy = sx1 - sx0, sy1 - sy0
        L2 = dx * dx + dy * dy
        u = 0.0 if L2 == 0 else max(0.0, min(1.0, ((x - sx0) * dx + (y - sy0) * dy) / L2))
        d = ((x - sx0 - u * dx) ** 2 + (y - sy0 - u * dy) ** 2) ** 0.5
        if d <= sw / 2 + dist:
            return True
    return False


# Mesh lines on the coplanar ground edges NEAR the tracks: without them openEMS
# moves the ground edge to the closest mesh line and the simulated gap can be
# very different from the real one.
for gx0, gy0, gx1, gy1 in M["ground"]:
    cy, cx = (gy0 + gy1) / 2, (gx0 + gx1) / 2
    for gx in (gx0, gx1):
        if _near_track(gx, cy):
            xlines.append(gx)
    for gy in (gy0, gy1):
        if _near_track(cx, gy):
            ylines.append(gy)

