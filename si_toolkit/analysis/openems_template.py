# 8 cells in the dielectric: the microstrip port integrates the field
# vertically, and with few cells the impedance reads too high.
# Dense vertical lines around the copper plane (z = h): the field in the
# coplanar gap is two-dimensional (width x height) and needs the same fineness
# in z as in y. Steps growing from fine_min up to res.
