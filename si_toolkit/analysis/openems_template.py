def _section_axes(mesh):
    """Axes of the cross-section in mm: (transverse position, z)."""
    xa = mesh[1] if section_axis == "x" else mesh[0]
    ya = mesh[2]
    scale = 1e3 if max(abs(xa).max(), abs(ya).max()) < 1 else 1.0
    return xa * scale, ya * scale


def _trace_center_across():
    """Transverse position (mm) of the centre of the track cut by the section."""
    for x0, y0, x1, y1, _w in M["segments"]:
        if section_axis == "x" and min(x0, x1) <= section_pos <= max(x0, x1):
            return (y0 + y1) / 2
        if section_axis == "y" and min(y0, y1) <= section_pos <= max(y0, y1):
            return (x0 + x1) / 2
    return None


# Trapezoidal integration (np.trapz was renamed in numpy 2)
_trapz = getattr(np, "trapezoid", None) or np.trapz


def _calibration(path):
    """
    Factor bringing the simulation fields to the real ones at voltage V_SIG.
    The line voltage is derived from the field itself: integral of Ez along z,
    under the track centre, from the plane (z=0) to the track (z=h). The peak
    over time is the pulse voltage.
    This way the result is in V/m whatever the internal unit of the file.
    Returns (factor, simulated voltage in file units).
    """
    frames, mesh, _times = _read_td_dump(path)
    xa, ya = _section_axes(mesh)
    c = _trace_center_across()
    if not frames or c is None:
        return None, None
    j = int(np.argmin(np.abs(xa - c)))  # column under the track centre
    rows = (ya >= 0) & (ya <= h)
    v_t = []
    for fr in frames:
        ez = fr[..., 2]
        if ez.shape == (len(xa), len(ya)):
            ez = ez.T
        v_t.append(abs(_trapz(ez[rows, j], ya[rows] * 1e-3)))
    v_sim = max(v_t)
    if v_sim <= 0:
        return None, None
    return V_SIG / v_sim, v_sim


def _make_gif(path, out_path, title, mode, k):
    """
    Animated GIF of the field with the real copper drawn on top.
    mode: "alto" = Ez in top view (V/mm, red/blue = direction),
          "campo" = |E| in the cross-section (V/mm),
          "energia" = energy density in the cross-section (J/m^3).
    k: calibration factor (see _calibration); None = relative units.
    Only the frames with significant field are kept.
    """
    import matplotlib.animation as anim
    from matplotlib.colors import PowerNorm, Normalize

    frames, mesh, times = _read_td_dump(path)
    if not frames:
        print(T("Nessun dato di campo in", "No field data in"), path)
        return
    kk = k if k else 1.0
    if mode == "alto":
        xa, ya = mesh[0], mesh[1]
        scale = 1e3 if max(abs(xa).max(), abs(ya).max()) < 1 else 1.0
        xa, ya = xa * scale, ya * scale
        lab = (T("x lungo la scheda (mm)", "x along the board (mm)"), "y (mm)")
    else:
        xa, ya = _section_axes(mesh)
        lab = (T("posizione trasversale (mm)", "transverse position (mm)"), T("z altezza (mm)", "z height (mm)"))
    # Dielectric constant per row (FR4 between 0 and h, air elsewhere)
    eps_rows = np.where((ya >= 0) & (ya <= h), er, 1.0)

    def value(fr):
        if mode == "alto":
            v = fr[..., 2] * kk / 1e3  # signed Ez, V/m -> V/mm
        else:
            v = np.sqrt((fr ** 2).sum(axis=-1)) * kk  # |E| in V/m
        if v.shape == (len(xa), len(ya)):
            v = v.T  # -> rows = second axis, columns = first axis
        if mode == "campo":
            v = v / 1e3  # V/mm
        elif mode == "energia":
            # Electric energy density 1/2*eps0*eps_r*|E|^2 (J/m^3): shows where
            # the signal really is (in the dielectric |E| is reduced by eps_r,
            # the energy is not)
            v = 0.5 * EPS0 * eps_rows[:, None] * v ** 2
        return v

    vals = [value(fr) for fr in frames]
    peak = [float(np.abs(v).max()) for v in vals]
    gmax = max(peak) or 1.0
    # Only the "live" frames: from the first to the last above 3% of the
    # maximum
    alive = [i for i, p in enumerate(peak) if p > 0.03 * gmax]
    if alive:
        i0, i1 = max(alive[0] - 1, 0), min(alive[-1] + 2, len(vals))
        vals, times = vals[i0:i1], times[i0:i1]

    # Peak frame: the one with the most field (the pulse is crossing the plane)
    i_peak = int(np.argmax([float((v ** 2).sum()) for v in vals]))
    # Framed area (cross-section): from the plane to 1 mm above the track
    if mode != "alto":
        xc = (xa.min() + xa.max()) / 2
        half = min((xa.max() - xa.min()) / 2, max(2.0, 2.5 * h))
        view = np.ix_(ya <= h + 1.0, (xa >= xc - half) & (xa <= xc + half))
    else:
        view = (slice(None), slice(None))
    sel = np.abs(vals[i_peak][view])
    # Color scale: 99th percentile of the peak frame in the framed area (the
    # hottest points on the copper corners do not decide it), or the fixed one
    # requested with --scale (in V/mm; converted for the energy)
    vmax = float(np.percentile(sel, 99.0)) or float(sel.max()) or 1.0
    if E_SCALE > 0 and k:
        if mode == "energia":
            vmax = 0.5 * EPS0 * er * (E_SCALE * 1e3) ** 2
        else:
            vmax = E_SCALE
    # Maximum field in the peak frame (99%: excludes the corners)
    e_info = ""
    if k and mode != "energia":
        e_info = f"  |  E max ~ {np.percentile(sel, 99.0):.0f} V/mm " + T("(aria cede a ~3000)", "(air breaks down at ~3000)")

    fig, ax = plt.subplots(figsize=(12, 5) if mode == "alto" else (10, 5))
    if mode == "alto":
        cmap, norm = "RdBu_r", Normalize(-vmax, vmax)
    else:
        # "Square root" scale: the strong field at the gap edges does not crush
        # the weaker field under the track to black
        cmap, norm = "inferno", PowerNorm(gamma=0.5, vmin=0, vmax=vmax)

    # The openEMS mesh is NOT uniform: pcolormesh uses the real coordinates of
    # every cell (imshow would place them at a constant step, distorting the
    # image)
    def edges(c):
        mid = (c[1:] + c[:-1]) / 2  # cell edges = midpoints between the nodes
        return np.concatenate(([c[0]], mid, [c[-1]]))
    im = ax.pcolormesh(edges(xa), edges(ya), vals[0], cmap=cmap, norm=norm, shading="flat")
    _draw_geometry(ax, "alto" if mode == "alto" else "sezione")
    if mode == "alto":
        ax.set_xlim(xa.min(), xa.max())
        ax.set_ylim(ya.min(), ya.max())
    else:
        ax.set_xlim(xc - half, xc + half)
        ax.set_ylim(-max(h * 0.08, 0.05), min(ya.max(), h + 1.0))  # room for the plane
    ax.set_aspect("equal")  # real 1:1 proportions
    ax.set_xlabel(lab[0])
    ax.set_ylabel(lab[1])
    unit = {"alto": T("Ez (V/mm, rosso/blu = verso)", "Ez (V/mm, red/blue = direction)"),
            "campo": T("|E| (V/mm, scala radice)", "|E| (V/mm, sqrt scale)"),
            "energia": T("energia (J/m^3, scala radice)", "energy (J/m^3, sqrt scale)")}[mode]
    if not k:
        unit = unit.split(" (")[0] + T(" (unita' relative)", " (relative units)")
    fig.colorbar(im, ax=ax, label=unit)
    head = f"{title}  -  " + T("segnale", "signal") + f" {V_SIG:g} V" if k else title
    ttl = ax.set_title(head)
    fig.tight_layout()

    def update(i):
        im.set_array(vals[i].ravel())  # pcolormesh: flattened data
        ttl.set_text(f"{head}  -  t = {times[i] * 1e9:.2f} ns" + (e_info if i == i_peak else ""))
        return im, ttl

    # Still image of the peak frame, next to the GIF
    update(i_peak)
    png_peak = os.path.splitext(out_path)[0] + "_peak.png"
    fig.savefig(png_peak, dpi=110)
    print(T("Creata", "Created") + f" {png_peak} (t = {times[i_peak] * 1e9:.2f} ns){e_info}")

    ani = anim.FuncAnimation(fig, update, frames=len(vals), interval=120, blit=False)
    ani.save(out_path, writer=anim.PillowWriter(fps=8))
    plt.close(fig)
    print(T("Creata {0} ({1} fotogrammi)", "Created {0} ({1} frames)").format(out_path, len(vals)))


