def merge_close(lines, min_gap):
    """
    Sorts the mesh lines and merges those closer than 'min_gap' (replacing
    them with their average). Cells that are too small force openEMS to a
    tiny time step and the simulation becomes extremely slow.
    """
    out = []
    for v in sorted(lines):
        if out and v - out[-1][-1] < min_gap:
            out[-1].append(v)
        else:
            out.append([v])
    return [sum(g) / len(g) for g in out]


# --- Fine mesh in the gap between track and coplanar ground ---
# For every straight segment the closest ground edge (within 1 mm) is looked
# for on each side and at least 8 cells are placed between track and ground:
# with few cells in the gap openEMS underestimates the impedance.
fine_min = res
gx_edges = sorted({v for r in M["ground"] for v in (r[0], r[2])})
gy_edges = sorted({v for r in M["ground"] for v in (r[1], r[3])})
for x0, y0, x1, y1, w in M["segments"]:
    if abs(y1 - y0) < 1e-6:  # horizontal segment: gap along y
        edges, center, add = gy_edges, y0, ylines
    elif abs(x1 - x0) < 1e-6:  # vertical segment: gap along x
        edges, center, add = gx_edges, x0, xlines
    else:
        continue
    for side in (1, -1):
        t_edge = center + side * w / 2
        cand = [e for e in edges if 0 < side * (e - t_edge) <= 1.0]
        if not cand:
            continue
        # Only "real" gaps: ground edges closer than 0.08 mm to the track are
        # almost always artifacts (pads, teardrops, bends) and would make tiny
        # cells, with a very small time step
        cand = [e for e in cand if abs(e - t_edge) >= 0.08]
        if not cand:
            continue
        g_edge = min(cand, key=lambda e: abs(e - t_edge))
        gap = abs(g_edge - t_edge)
        n = 8
        add += list(np.linspace(t_edge, g_edge, n + 1))
        # Cell in the gap never below 0.02 mm
        fine_min = min(fine_min, max(gap / n, 0.02))
print(T("Cella minima nel gap:", "Smallest cell in the gap:") + f" {fine_min:.3f} mm")

xlines = merge_close(xlines, max(min(res / 3, fine_min * 0.6), 0.012))
ylines = merge_close(ylines, max(min(res / 3, fine_min * 0.6), 0.012))

